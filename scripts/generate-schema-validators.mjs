import { createHash } from "node:crypto";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import process from "node:process";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { build } from "esbuild";

const root = new URL("../", import.meta.url);
const targets = [
  {
    source: new URL("inspection/rule-schema.v1.json", root),
    output: new URL("lib/generated/rule-schema-validator.mjs", root),
  },
  {
    source: new URL("inspection/spec-extraction-output-schema.v1.json", root),
    output: new URL("lib/generated/spec-extraction-validator.mjs", root),
  },
];
const checkOnly = process.argv.includes("--check");

async function generate(schemaText, sourcefile) {
  const schema = JSON.parse(schemaText);
  const ajv = new Ajv2020({ allErrors: true, strict: true, code: { esm: true, source: true } });
  ajv.addSchema(schema, "runtimeContract");
  const digest = createHash("sha256").update(schemaText).digest("hex");
  const bundled = await build({
    stdin: { contents: standaloneCode(ajv, { validate: "runtimeContract" }), loader: "js", sourcefile, resolveDir: fileURLToPath(root) },
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    write: false,
    minify: false,
    logLevel: "silent",
  });
  return `// Generated by scripts/generate-schema-validators.mjs. Do not edit.\n// schema-sha256: ${digest}\n${bundled.outputFiles[0].text}`;
}

let stale = false;
for (const target of targets) {
  const schemaText = await readFile(target.source, "utf8");
  const generated = await generate(schemaText, target.output.pathname.split("/").at(-1));
  let current = "";
  try { current = await readFile(target.output, "utf8"); } catch { /* Generated file does not exist yet. */ }
  if (current === generated) continue;
  if (checkOnly) {
    stale = true;
    console.error(`${target.output.pathname} is not generated from its current schema.`);
  } else {
    await mkdir(new URL("./", target.output), { recursive: true });
    await writeFile(target.output, generated, "utf8");
    console.log(`Generated ${target.output.pathname}`);
  }
}
if (stale) process.exitCode = 1;
